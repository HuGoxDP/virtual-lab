// scripts/build-icons.mjs
//
// Generates src/app/ui/icon/icon-data.generated.ts: the path data of the Phosphor icons the site
// hosts itself (@phosphor-icons/core, MIT, regular weight). One list — ICON_NAMES below — decides
// both which icons ship and which ones the admin pickers offer, so a font (5.5 MB) or a CDN
// (a CSP change) is never needed.
//
//   node scripts/build-icons.mjs           write the file
//   node scripts/build-icons.mjs --check   exit 1 when the committed file is stale
//   node scripts/build-icons.mjs --stdout  print instead of writing
//
// Only icons made of plain <path d="..."> elements are accepted: the component renders
// <svg><path [attr.d]>, with no innerHTML and nothing to sanitise.

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SVG_DIR = join(ROOT, 'node_modules/@phosphor-icons/core/assets/regular');
const OUTPUT = join(ROOT, 'src/app/ui/icon/icon-data.generated.ts');

/** Every icon of the prototype screens (site + admin). */
const PROTOTYPE_ICONS = `angle arrow-counter-clockwise arrow-left arrow-right arrow-square-out arrow-u-up-left
  arrows-clockwise atom bank bone browser calendar-blank chart-bar chart-line chat-text check check-circle clock
  clock-clockwise clock-counter-clockwise corners-out cube cube-transparent dna download-simple eye eye-slash file
  file-code file-html file-image file-js file-zip flask folder folders funnel gauge graduation-cap grid-four keyboard
  lightning link-simple list list-dashes magnifying-glass map-pin mouse-left-click mouse-scroll paper-plane-tilt path
  pause pencil-simple person-simple-walk planet play play-circle plus ruler scissors seal-check selection shield-check
  shuffle sign-in sign-out sliders sliders-horizontal square-split-horizontal squares-four stack tag text-aa translate
  trash tray upload-simple user user-focus video-camera warning warning-circle wave-sine x`;

/** The categories migration 006 seeds (physics, biology, chemistry, history, astronomy, test, other). */
const CATEGORY_ICONS = 'lightning dna flask bank planet cube folder';

/** Extra choices for "Що всередині" items and categories, beyond what the prototype itself uses. */
const PICKER_ICONS = `arrows-in arrows-out brain bug camera circuitry compass copy cpu crosshair cube-focus cursor-click
  drop engine fire function gear globe graph hand-pointing heart hexagon info leaf lightbulb magnet
  magnifying-glass-plus map-trifold microscope moon palette question rocket share-network shapes sigma speaker-high
  speedometer star sun target test-tube thermometer timer tree triangle wind books book-open`;

const words = text => text.split(/\s+/).filter(Boolean);

/** The one list: sorted and de-duplicated so the generated file is stable. */
export const ICON_NAMES = [...new Set([PROTOTYPE_ICONS, CATEGORY_ICONS, PICKER_ICONS].flatMap(words))].sort();

const PATH_ELEMENT = /<path d="([^"]+)"\/>/g;

/** Path data of one Phosphor SVG; throws on anything that is not a bare set of <path d> elements. */
export function parsePaths(name, svg) {
  const root = svg.trim().match(/^<svg\b([^>]*)>([\s\S]*)<\/svg>$/);
  if (!root) throw new Error(`Icon "${name}": not an <svg> document`);
  if (!/viewBox="0 0 256 256"/.test(root[1])) throw new Error(`Icon "${name}": viewBox is not 0 0 256 256`);

  const paths = [...root[2].matchAll(PATH_ELEMENT)].map(m => m[1]);
  if (paths.length === 0 || root[2].replace(PATH_ELEMENT, '').trim() !== '') {
    throw new Error(`Icon "${name}" is not path-only (it has other elements or path attributes)`);
  }
  return paths;
}

/** The generated TypeScript module. Pure: `readSvg(name)` supplies the SVG text. */
export function renderIconModule(names, readSvg) {
  const entries = names.map(name => {
    const paths = parsePaths(name, readSvg(name)).map(d => `'${d}'`).join(', ');
    return `  '${name}': [${paths}],`;
  });
  return [
    '// path: src/app/ui/icon/icon-data.generated.ts',
    '// GENERATED by scripts/build-icons.mjs from @phosphor-icons/core (MIT, regular weight). Do not edit:',
    '// change ICON_NAMES in the script and run `npm run icons`.',
    '',
    '/** Every hosted icon. The same list feeds <vl-icon> and the admin pickers. */',
    `export const ICON_NAMES: readonly string[] = [${names.map(n => `'${n}'`).join(', ')}];`,
    '',
    '/** Icon name -> the `d` attribute of each <path> in its 256x256 viewBox. */',
    'export const ICON_PATHS: Readonly<Record<string, readonly string[]>> = {',
    ...entries,
    '};',
    '',
  ].join('\n');
}

function readPhosphorSvg(name) {
  const file = join(SVG_DIR, `${name}.svg`);
  if (!existsSync(file)) throw new Error(`Icon "${name}" does not exist in @phosphor-icons/core (regular)`);
  return readFileSync(file, 'utf8');
}

function main(args) {
  const text = renderIconModule(ICON_NAMES, readPhosphorSvg);
  if (args.includes('--stdout')) {
    process.stdout.write(text);
  } else if (args.includes('--check')) {
    const current = existsSync(OUTPUT) ? readFileSync(OUTPUT, 'utf8').replace(/\r\n/g, '\n') : '';
    if (current !== text) {
      console.error('icon-data.generated.ts is stale: run `npm run icons`.');
      process.exitCode = 1;
    }
  } else {
    writeFileSync(OUTPUT, text);
    console.log(`Wrote ${ICON_NAMES.length} icons to ${OUTPUT}`);
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main(process.argv.slice(2));
